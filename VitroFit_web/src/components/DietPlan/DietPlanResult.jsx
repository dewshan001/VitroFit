import { useState, useEffect } from 'react';

const MEAL_ICONS = {
  breakfast: '🍳',
  lunch: '🥗',
  dinner: '🍽️',
  snack: '🍎',
};

const MEAL_FALLBACK_ICON = '🍽️';

/** Shared summary + meal breakdown, used by both the unsaved result preview and a saved plan's read-only view. */
function PlanDetails({ plan, hasMedicalConditions }) {
  const totalCalories = plan?.totalCalories ?? 0;
  const macros = plan?.macros ?? { protein: 0, carbs: 0, fat: 0 };
  const meals = plan?.meals ?? [];

  const mealCalories = (meal) =>
    (meal.items || []).reduce((sum, item) => sum + (item.calories || 0), 0);
  const icon = (type) => MEAL_ICONS[type?.toLowerCase()] || MEAL_FALLBACK_ICON;

  return (
    <>
      {/* Disclaimer — always shown, more prominent when medical conditions were selected */}
      <div className={`dp-disclaimer${hasMedicalConditions ? ' dp-disclaimer-strong' : ''}`}>
        This plan is generated by AI and is not medical advice.
        {hasMedicalConditions
          ? ' Given the medical condition(s) you selected, please consult a doctor or dietitian before following it.'
          : ' Consult a doctor or dietitian for guidance specific to your health.'}
      </div>

      {plan?.withinTolerance === false && (
        <div className="dp-warning-banner">
          This plan's totals may not exactly match your calorie/macro targets. You can
          regenerate it, or edit the meals below before confirming.
        </div>
      )}

      {/* Summary bar */}
      <div className="dp-summary">
        <div className="dp-summary-item">
          <span className="dp-summary-value">{totalCalories}</span>
          <span className="dp-summary-label">Daily Calories</span>
        </div>
        <div className="dp-summary-item">
          <span className="dp-summary-value">{macros.protein}g</span>
          <span className="dp-summary-label">Protein</span>
        </div>
        <div className="dp-summary-item">
          <span className="dp-summary-value">{macros.carbs}g</span>
          <span className="dp-summary-label">Carbs</span>
        </div>
        <div className="dp-summary-item">
          <span className="dp-summary-value">{macros.fat}g</span>
          <span className="dp-summary-label">Fat</span>
        </div>
      </div>

      {/* Meal cards */}
      <div className="dp-meals">
        {meals.map((meal, i) => (
          <div className="dp-meal" key={i}>
            <div className="dp-meal-head">
              <span className="dp-meal-icon">{icon(meal.type)}</span>
              <h3 className="dp-meal-title">{meal.label}</h3>
              <span className="dp-meal-calories">{mealCalories(meal)} kcal</span>
            </div>
            <ul className="dp-meal-items">
              {(meal.items || []).map((item, j) => (
                <li className="dp-meal-item" key={j}>
                  <div className="dp-meal-item-info">
                    <span className="dp-meal-item-name">{item.name}</span>
                    <span className="dp-meal-item-portion">{item.portion}</span>
                  </div>
                  <div className="dp-meal-item-meta">
                    <span className="dp-meal-item-cal">{item.calories} kcal</span>
                    <span className="dp-meal-item-macros">
                      P {item.macros?.protein ?? 0} · C {item.macros?.carbs ?? 0} · F {item.macros?.fat ?? 0}
                    </span>
                  </div>
                </li>
              ))}
            </ul>
          </div>
        ))}
      </div>
    </>
  );
}

function formatDate(iso) {
  return new Date(iso).toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
}

/**
 * Diet plan results/display component.
 *
 * Handles states:
 *  - empty:   no plans ever saved yet (call to action to build the first one)
 *  - browse:  the logged-in user's saved plans, browsable with edit/delete/view
 *  - view:    a single saved plan's full read-only breakdown
 *  - loading: skeleton while the AI generates the plan
 *  - error:   the backend call failed (network, timeout, or the LLM couldn't produce a valid plan)
 *  - result:  a freshly generated (not yet saved) meal plan broken down by meal with macros & totals
 */
export default function DietPlanResult({
  state,
  plan,
  errorMessage,
  errorSteps = [],
  liveSteps = [],
  hasMedicalConditions,
  confirmStatus = 'idle',
  confirmErrorMessage,
  savedPlans = [],
  onGenerate,
  onEdit,
  onRegenerate,
  onConfirm,
  onCreateNew,
  onViewPlan,
  onEditPlan,
  onDeletePlan,
  onBack,
  onDelete,
  onRefine,
  refineStatus = 'idle',
  refineMessage = '',
  refineLiveSteps = [],
}) {
  if (state === 'empty') {
    return (
      <div className="dp-empty dp-fade-up">
        <div className="dp-empty-icon">🍽️</div>
        <h2 className="dp-empty-title">No Diet Plan Yet</h2>
        <p className="dp-empty-desc">
          Answer a few quick questions about your body, goals, and dietary
          preferences and we'll generate a personalised plan for you.
        </p>
        <button className="btn-primary" onClick={onGenerate}>
          Create a New Plan
        </button>
      </div>
    );
  }

  if (state === 'browse') {
    return (
      <div className="dp-browse dp-fade-up">
        <div className="dp-browse-head">
          <h2 className="dp-browse-title">Your Diet Plans</h2>
          <button className="btn-primary" onClick={onCreateNew}>
            + Create Another Plan
          </button>
        </div>
        <div className="dp-browse-list">
          {savedPlans.map((sp) => (
            <div
              className="dp-browse-card"
              key={sp.id}
              role="button"
              tabIndex={0}
              onClick={() => onViewPlan(sp)}
              onKeyDown={(e) => { if (e.key === 'Enter') onViewPlan(sp); }}
            >
              <div className="dp-browse-card-info">
                <span className="dp-browse-card-date">{formatDate(sp.createdAt)}</span>
                <span className="dp-browse-card-cal">{sp.totalCalories} kcal/day</span>
              </div>
              <div className="dp-browse-card-actions">
                <button
                  className="btn-secondary"
                  onClick={(e) => { e.stopPropagation(); onEditPlan(sp); }}
                >
                  Edit
                </button>
                <button
                  className="btn-secondary dp-btn-danger"
                  onClick={(e) => { e.stopPropagation(); onDeletePlan(sp.id); }}
                >
                  Delete
                </button>
              </div>
            </div>
          ))}
        </div>
      </div>
    );
  }

  if (state === 'view') {
    return (
      <div className="dp-result dp-fade-up">
        <PlanDetails plan={plan} hasMedicalConditions={hasMedicalConditions} />
        <div className="dp-result-actions">
          <button className="btn-secondary" onClick={onBack}>
            Back to My Plans
          </button>
          <button className="btn-secondary" onClick={onEdit}>
            Edit
          </button>
          <button className="btn-secondary dp-btn-danger" onClick={onDelete}>
            Delete
          </button>
        </div>
      </div>
    );
  }

  if (state === 'error') {
    const attemptSteps = (errorSteps || []).filter((s) => s.agent === 'SafetyValidatorAgent');
    return (
      <div className="dp-empty dp-fade-up">
        <div className="dp-empty-icon">⚠️</div>
        <h2 className="dp-empty-title">Couldn't Generate Your Plan</h2>
        <p className="dp-empty-desc">
          {errorMessage || 'Something went wrong while generating your diet plan. Please try again.'}
        </p>
        {attemptSteps.length > 0 && (
          <div className="dp-disclaimer" style={{ textAlign: 'left', marginTop: '1rem' }}>
            <p style={{ margin: 0 }}>
              Our system tried {attemptSteps.length === 1 ? 'once' : `${attemptSteps.length} times`} to build a
              plan around your preferences:
            </p>
            <ul style={{ margin: '0.5rem 0 0', paddingLeft: '1.25rem' }}>
              {attemptSteps.map((step, i) => (
                <li key={i}>{describeAttemptStep(step)}</li>
              ))}
            </ul>
          </div>
        )}
        <div className="dp-result-actions">
          <button className="btn-secondary" onClick={onEdit}>
            Edit Preferences
          </button>
          <button className="btn-primary" onClick={onRegenerate}>
            Try Again
          </button>
        </div>
      </div>
    );
  }

  if (state === 'loading') {
    return (
      <div className="dp-loading dp-fade-up">
        <div className="dp-loading-top">
          <span className="dp-loader" />
          <h3 className="dp-loading-title">Generating your diet plan…</h3>
          {liveSteps.length === 0 ? (
            <p className="dp-loading-desc">
              <AgentProgressText />
            </p>
          ) : (
            <ul className="dp-loading-desc" style={{ textAlign: 'left', listStyle: 'none', padding: 0, margin: '0.5rem 0 0' }}>
              {liveSteps.map((step, i) => (
                <li key={i}>{describeLiveStep(step)}</li>
              ))}
            </ul>
          )}
        </div>
        <div className="dp-skeleton-list">
          {[0, 1, 2, 3].map((m) => (
            <div className="dp-skeleton-meal" key={m}>
              <div className="dp-skeleton-label shimmer" />
              <div className="dp-skeleton-rows">
                {[0, 1, 2].map((r) => (
                  <div className="dp-skeleton-line shimmer" key={r} />
                ))}
              </div>
            </div>
          ))}
        </div>
      </div>
    );
  }

  // state === 'result'
  return (
    <div className="dp-result dp-fade-up">
      <PlanDetails plan={plan} hasMedicalConditions={hasMedicalConditions} />

      <RefineBox
        onRefine={onRefine}
        refineStatus={refineStatus}
        refineMessage={refineMessage}
        refineLiveSteps={refineLiveSteps}
      />

      {/* Actions */}
      <div className="dp-result-actions">
        <button className="btn-secondary" onClick={onEdit}>
          Start Over
        </button>
        <button
          className="btn-primary"
          onClick={onConfirm}
          disabled={confirmStatus === 'saving' || confirmStatus === 'saved'}
        >
          {confirmStatus === 'saving' && 'Saving…'}
          {confirmStatus === 'saved' && 'Plan Saved ✓'}
          {(confirmStatus === 'idle' || confirmStatus === 'error') && 'Confirm Plan'}
        </button>
      </div>
      {confirmStatus === 'error' && (
        <p className="dp-field-err-text">
          {confirmErrorMessage || "Couldn't save your plan. Please try again."}
        </p>
      )}
      {confirmStatus === 'saved' && (
        <div className="dp-result-secondary-actions">
          <button className="btn-secondary" onClick={onBack}>
            Back to My Plans
          </button>
        </div>
      )}
    </div>
  );
}

/* Cycles through what the three agents are actually doing, in order, while
   the (single, synchronous) /generate request is in flight. Not a live feed
   of the real backend step - the request doesn't stream progress - but the
   labels and order match the real agent sequence in workflow.build_plan(). */
const AGENT_PROGRESS_STEPS = [
  'Nutrition Analyst is calculating your calorie and macro targets…',
  'Meal Generator is drafting a full day of meals…',
  'Safety Validator is checking the plan against your restrictions and limits…',
];

function AgentProgressText() {
  const [stepIndex, setStepIndex] = useState(0);

  useEffect(() => {
    const interval = setInterval(() => {
      setStepIndex((i) => Math.min(i + 1, AGENT_PROGRESS_STEPS.length - 1));
    }, 4000);
    return () => clearInterval(interval);
  }, []);

  return AGENT_PROGRESS_STEPS[stepIndex];
}

/**
 * Turns one real completedSteps entry (as polled live from
 * GET /workflows/{id}) into a plain-language progress line. This reflects
 * what the backend has actually finished, not a simulated guess.
 */
function describeLiveStep(step) {
  if (step.agent === 'NutritionAnalystAgent') {
    return step.step === 1
      ? '✓ Nutrition Analyst calculated your calorie and macro targets.'
      : '✓ Nutrition Analyst checked whether this plan needs extra safety review.';
  }
  if (step.agent === 'MealGeneratorAgent') {
    if (step.refine) return '✓ Meal Generator applied your requested change.';
    return step.retry
      ? `↻ Meal Generator drafted a revised set of meals (try ${step.retry + 1}).`
      : '✓ Meal Generator drafted a full day of meals.';
  }
  if (step.agent === 'SafetyValidatorAgent') {
    if (step.refine) {
      if (step.verdict === 'reject') return '✗ Safety Validator found that change would break one of your restrictions.';
      return '✓ Safety Validator confirmed the change is still safe.';
    }
    if (step.verdict === 'pass') return '✓ Safety Validator confirmed the plan meets your targets.';
    if (step.verdict === 'reject') return '✗ Safety Validator found a safety issue with this plan.';
    return `↻ Safety Validator flagged this attempt as not quite on target — asking for another try.`;
  }
  return `✓ ${step.agent} finished.`;
}

/** A free-text "edit this plan" box, used on the result screen instead of restarting the whole form. */
function RefineBox({ onRefine, refineStatus, refineMessage, refineLiveSteps }) {
  const [instruction, setInstruction] = useState('');
  if (!onRefine) return null;

  const applying = refineStatus === 'applying';

  const handleSubmit = (e) => {
    e.preventDefault();
    const trimmed = instruction.trim();
    if (!trimmed || applying) return;
    onRefine(trimmed);
    setInstruction('');
  };

  return (
    <div className="dp-disclaimer" style={{ textAlign: 'left', marginBottom: '1rem' }}>
      <p style={{ margin: '0 0 0.5rem', fontWeight: 600 }}>Want a small change?</p>
      <form onSubmit={handleSubmit} style={{ display: 'flex', gap: '0.5rem', flexWrap: 'wrap' }}>
        <input
          type="text"
          value={instruction}
          onChange={(e) => setInstruction(e.target.value)}
          placeholder="e.g. instead of rice, include something else at lunch"
          disabled={applying}
          maxLength={300}
          style={{
            flex: '1 1 260px', padding: '0.55rem 0.75rem', borderRadius: '6px',
            border: '1px solid var(--border)', background: 'var(--bg-card)', color: 'inherit',
          }}
        />
        <button type="submit" className="btn-secondary" disabled={applying || !instruction.trim()}>
          {applying ? 'Applying…' : 'Apply Change'}
        </button>
      </form>
      {applying && (
        <ul style={{ margin: '0.5rem 0 0', paddingLeft: '1.25rem' }}>
          {refineLiveSteps.length === 0 ? (
            <li>Looking at your plan…</li>
          ) : (
            refineLiveSteps.filter((s) => s.refine).map((s, i) => <li key={i}>{describeLiveStep(s)}</li>)
          )}
        </ul>
      )}
      {(refineStatus === 'note' || refineStatus === 'error') && refineMessage && (
        <p className="dp-field-err-text" style={{ marginTop: '0.5rem' }}>{refineMessage}</p>
      )}
    </div>
  );
}

/** Plain-language, non-technical summary of one validator attempt, for customers rather than engineers. */
function describeAttemptStep(step) {
  const tryLabel = step.attempt ? `Try ${step.attempt}` : 'This try';
  const isSafetyIssue = (step.violations || []).some((v) => v.code === 'RESTRICTION_VIOLATION' || v.code === 'BELOW_SAFE_FLOOR');

  if (step.verdict === 'pass') {
    return `${tryLabel}: matched your calorie target and passed all checks.`;
  }
  if (isSafetyIssue) {
    // A dietary-safety issue (an ingredient conflicting with a restriction/
    // allergy, or a target below a safe calorie floor) is the real reason,
    // not the calorie miss - lead with that in plain terms.
    return `${tryLabel}: one of the suggested meals conflicted with a restriction, allergy, or safe calorie minimum you set.`;
  }
  if (step.targetCalories) {
    const direction = step.attemptCalories < step.targetCalories ? 'short of' : 'over';
    return `${tryLabel}: came out to about ${step.attemptCalories} calories — ${step.diffPct}% ${direction} your ${step.targetCalories}-calorie target.`;
  }
  return `${tryLabel}: didn't quite match your preferences.`;
}